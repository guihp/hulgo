-- Permite vários lembretes do mesmo prazo no mesmo dia.
-- Antes o PK (prazo_id, alerta_dia, tipo) fazia o 2º lembrete cair em 23505
-- ("já notificado") e nunca disparar push.

alter table public.app_prazos_alertas
  drop constraint if exists app_prazos_alertas_pkey;

alter table public.app_prazos_alertas
  add column if not exists id bigint generated by default as identity;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'app_prazos_alertas_id_pkey'
  ) then
    alter table public.app_prazos_alertas
      add constraint app_prazos_alertas_id_pkey primary key (id);
  end if;
end$$;

create unique index if not exists app_prazos_alertas_legacy_uidx
  on public.app_prazos_alertas (prazo_id, alerta_dia, tipo)
  where lembrete_id is null;

create unique index if not exists app_prazos_alertas_lembrete_uidx
  on public.app_prazos_alertas (lembrete_id)
  where lembrete_id is not null;

-- Multi-lembretes por prazo (substitui o fluxo lembrar_em pontual no cron).
-- Deadline = data_prazo + hora_prazo (America/Sao_Paulo); hora_prazo null = 23:59:59 SP.
-- fire_at = deadline - offset_minutes. Ver também /api/cron/prazos-notificar.

create table if not exists public.app_prazos_lembretes (
  id              bigint generated by default as identity primary key,
  prazo_id        bigint not null references public.app_prazos (id) on delete cascade,
  offset_minutes  integer not null check (offset_minutes >= 0),
  label           text,
  created_at      timestamptz not null default now(),
  constraint app_prazos_lembretes_prazo_offset_key unique (prazo_id, offset_minutes)
);

create index if not exists app_prazos_lembretes_prazo_idx
  on public.app_prazos_lembretes (prazo_id);

alter table public.app_prazos_lembretes enable row level security;

drop policy if exists "prazos_lembretes_select" on public.app_prazos_lembretes;
create policy "prazos_lembretes_select" on public.app_prazos_lembretes
  for select to authenticated
  using (true);

drop policy if exists "prazos_lembretes_insert" on public.app_prazos_lembretes;
create policy "prazos_lembretes_insert" on public.app_prazos_lembretes
  for insert to authenticated
  with check (true);

drop policy if exists "prazos_lembretes_update" on public.app_prazos_lembretes;
create policy "prazos_lembretes_update" on public.app_prazos_lembretes
  for update to authenticated
  using (true)
  with check (true);

drop policy if exists "prazos_lembretes_delete" on public.app_prazos_lembretes;
create policy "prazos_lembretes_delete" on public.app_prazos_lembretes
  for delete to authenticated
  using (true);

comment on table public.app_prazos_lembretes is
  'Lembretes configuráveis: push em (deadline SP EOD - offset_minutes). offset 0 = na hora do prazo.';
comment on column public.app_prazos_lembretes.offset_minutes is
  'Minutos antes do fim do dia (America/Sao_Paulo) de data_prazo. 0 = somente no horário (deadline).';

-- Dedupe de envio por lembrete
alter table public.app_prazos_alertas
  add column if not exists lembrete_id bigint references public.app_prazos_lembretes (id) on delete cascade;

alter table public.app_prazos_alertas
  drop constraint if exists app_prazos_alertas_tipo_check;

alter table public.app_prazos_alertas
  add constraint app_prazos_alertas_tipo_check
  check (tipo = any (array['hoje'::text, 'amanha'::text, 'lembrar'::text, 'lembrete'::text]));

create unique index if not exists app_prazos_alertas_lembrete_uidx
  on public.app_prazos_alertas (lembrete_id)
  where lembrete_id is not null;

comment on table public.app_prazos_alertas is
  'Dedupe de push de prazos. Novos envios usam tipo=lembrete + lembrete_id. hoje/amanha/lembrar são legado.';

comment on column public.app_prazos.lembrar_em is
  'DEPRECATED: use app_prazos_lembretes. Mantido só para leitura histórica; cron novo ignora.';

-- Seed default 1h + na hora para prazos abertos sem lembretes
insert into public.app_prazos_lembretes (prazo_id, offset_minutes, label)
select p.id, v.offset_minutes, v.label
from public.app_prazos p
cross join (values
  (60, '1 hora antes'),
  (0, 'Somente no horário')
) as v(offset_minutes, label)
where not p.concluido
  and not exists (
    select 1 from public.app_prazos_lembretes l where l.prazo_id = p.id
  )
on conflict (prazo_id, offset_minutes) do nothing;

-- Endurece webhook: falha de push não bloqueia INSERT de negócio
create or replace function public.notify_painel_push_webhook()
returns trigger
language plpgsql
security definer
set search_path = public, net, extensions
as $$
declare
  webhook_url text := 'https://advocacia.iafeoficial.com/api/push/webhook';
  webhook_secret text := '8ba368f9fe57eb473005e85252c8817686d57eeaa0602c75b844304a7634264f';
  payload jsonb;
  request_id bigint;
begin
  payload := jsonb_build_object(
    'type', tg_op,
    'table', tg_table_name,
    'schema', tg_table_schema,
    'record', case when tg_op = 'DELETE' then null else to_jsonb(new) end,
    'old_record', case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) else null end
  );

  begin
    select net.http_post(
      url := webhook_url,
      body := payload,
      params := '{}'::jsonb,
      headers := jsonb_build_object(
        'Content-Type', 'application/json',
        'x-push-webhook-secret', webhook_secret
      ),
      timeout_milliseconds := 5000
    ) into request_id;
  exception when others then
    raise warning 'notify_painel_push_webhook: %', sqlerrm;
  end;

  return coalesce(new, old);
end;
$$;

comment on function public.notify_painel_push_webhook() is
  'Dispara Web Push via POST /api/push/webhook. Falhas de rede não abortam o INSERT (aprovacoes/prazos/etc).';

-- Reafirma triggers (idempotente) — painel e n8n usam INSERT normal
drop trigger if exists push_webhook_aprovacoes_pendentes_insert on public.aprovacoes_pendentes;
create trigger push_webhook_aprovacoes_pendentes_insert
  after insert on public.aprovacoes_pendentes
  for each row
  execute function public.notify_painel_push_webhook();

drop trigger if exists push_webhook_app_prazos_insert on public.app_prazos;
create trigger push_webhook_app_prazos_insert
  after insert on public.app_prazos
  for each row
  execute function public.notify_painel_push_webhook();

-- Web Push subscriptions + dedupe de alertas de prazo
create table if not exists public.app_push_subscriptions (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null references auth.users (id) on delete cascade,
  endpoint     text not null,
  p256dh       text not null,
  auth         text not null,
  user_agent   text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint app_push_subscriptions_endpoint_key unique (endpoint)
);

create index if not exists app_push_subscriptions_user_idx
  on public.app_push_subscriptions (user_id);

alter table public.app_push_subscriptions enable row level security;

drop policy if exists "push_subs_select_own" on public.app_push_subscriptions;
create policy "push_subs_select_own" on public.app_push_subscriptions
  for select to authenticated
  using (user_id = auth.uid());

drop policy if exists "push_subs_insert_own" on public.app_push_subscriptions;
create policy "push_subs_insert_own" on public.app_push_subscriptions
  for insert to authenticated
  with check (
    user_id = auth.uid()
    and exists (
      select 1 from public.app_usuarios u
      where u.id = auth.uid() and u.ativo = true
    )
  );

drop policy if exists "push_subs_update_own" on public.app_push_subscriptions;
create policy "push_subs_update_own" on public.app_push_subscriptions
  for update to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists "push_subs_delete_own" on public.app_push_subscriptions;
create policy "push_subs_delete_own" on public.app_push_subscriptions
  for delete to authenticated
  using (user_id = auth.uid());

comment on table public.app_push_subscriptions is
  'Subscriptions Web Push por usuário (endpoint + keys VAPID)';

-- Dedupe: alerta de prazo (hoje/amanhã) enviado 1× por dia
create table if not exists public.app_prazos_alertas (
  prazo_id    bigint not null references public.app_prazos (id) on delete cascade,
  alerta_dia  date not null,
  tipo        text not null check (tipo in ('hoje', 'amanha')),
  enviado_em  timestamptz not null default now(),
  primary key (prazo_id, alerta_dia, tipo)
);

alter table public.app_prazos_alertas enable row level security;

-- Só service role / cron escreve; authenticated pode ler (opcional)
drop policy if exists "prazos_alertas_select" on public.app_prazos_alertas;
create policy "prazos_alertas_select" on public.app_prazos_alertas
  for select to authenticated
  using (true);

comment on table public.app_prazos_alertas is
  'Controle de envio diário de push de prazos (hoje/amanhã)';
